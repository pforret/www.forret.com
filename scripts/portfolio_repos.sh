#!/usr/bin/env bash
# Generate docs/portfolio/opensource.md from the GitHub repos of a user.
# Selects non-fork, non-archived repos with at least MIN_STARS stars, grouped by theme.
# Requires: gh (authenticated), jq.  Deterministic: same GitHub data => same output (except date line).
set -euo pipefail

GH_USER="${GH_USER:-pforret}"
MIN_STARS="${MIN_STARS:-5}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT="${OUTPUT:-$ROOT/docs/portfolio/opensource.md}"

usage() {
  cat <<EOF
Usage: $(basename "$0") [-h]
  Rewrite $OUTPUT with all non-fork, non-archived GitHub repos of '$GH_USER'
  with >= $MIN_STARS stars, grouped by theme.
  Env overrides: GH_USER, MIN_STARS, OUTPUT
EOF
}

[[ "${1:-}" == "-h" || "${1:-}" == "--help" ]] && { usage; exit 0; }
for bin in gh jq; do
  command -v "$bin" >/dev/null || { echo "ERROR: '$bin' is required" >&2; exit 1; }
done

# Theme groups, in display order. Repos not listed end up in "Other".
GROUPS_JSON='[
  {"title": "Bash frameworks & tools", "icon": ":material-bash:",
   "repos": ["bashew","setver","progressbar","rexec","note","shtext","shlorem","shini","shwordle","awk-boilerplate","bash_benchmarks","LearnBashQuickly"]},
  {"title": "Sysadmin, network & macOS", "icon": ":material-server-network:",
   "repos": ["m1_homebrew","crontask","glennr-unifi","wp_cleanup","bumpkeys","font","WinAdmin","netcheck","landeploy","ghlookup"]},
  {"title": "Media & AI", "icon": ":material-image-filter-hdr:",
   "repos": ["splashmark","shmixcloud","m1fusion"]},
  {"title": "Docs & developer tooling", "icon": ":material-tools:",
   "repos": ["mkdox","PeakClaude"]}
]'

repos_json="$(gh api "users/$GH_USER/repos?per_page=100" --paginate \
  --jq ".[] | select(.fork == false and .archived == false and .stargazers_count >= $MIN_STARS)
        | {name, description, stars: .stargazers_count, url: .html_url, homepage, language}" |
  jq -s 'sort_by(-.stars, (.name | ascii_downcase))')"

mkdir -p "$(dirname "$OUTPUT")"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  echo "---"
  echo "title: Open source"
  echo "description: Open-source projects by Peter Forret on GitHub, grouped by theme"
  echo "---"
  echo "<!-- generated by scripts/portfolio_repos.sh on $(date +%Y-%m-%d) — do not edit, rerun the script -->"
  echo
  echo "# Open source on GitHub"
  echo
  echo "A selection of my [public GitHub repositories](https://github.com/$GH_USER?tab=repositories):"
  echo "every original (non-fork) project with at least $MIN_STARS :octicons-star-16:, grouped by theme."
  echo "Most of them are Bash tools built on [bashew](bashew.md)."
  echo
  jq -r --argjson groups "$GROUPS_JSON" '
    def esc: gsub("\\|"; "\\|") | gsub("<"; "&lt;") | gsub(">"; "&gt;");
    def entry: "- **[\(.name)](\(.url))** · \(.stars) :octicons-star-16:"
               + (if .language then " · `\(.language)`" else "" end)
               + "  \n  \((.description // "–") | esc)"
               + (if (.homepage // "") != "" then " · [:octicons-link-external-16: site](\(.homepage))" else "" end);
    . as $repos
    | ([$groups[].repos[]]) as $mapped
    | ($groups + [{title: "Other", icon: ":material-dots-horizontal:", repos: [$repos[].name | select(. as $n | $mapped | index($n) | not)]}])
    | map(. as $g | {title, icon, items: [$repos[] | select(.name as $n | $g.repos | index($n))]})
    | map(select(.items | length > 0))
    | .[]
    | "## \(.icon) \(.title)\n\n" + ([.items[] | entry] | join("\n")) + "\n"
  ' <<<"$repos_json"
} >"$tmp"

mv "$tmp" "$OUTPUT"
trap - EXIT
count="$(jq length <<<"$repos_json")"
echo "Wrote $count repos to ${OUTPUT#"$ROOT"/}"
